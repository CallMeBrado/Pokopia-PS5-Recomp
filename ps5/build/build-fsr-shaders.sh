#!/bin/bash
# Compile the FSR 1 present shaders (gfx-bridge/shaders/fsr_*.comp, AMD's
# MIT-licensed ffx headers) to SPIR-V and embed them in gfx-bridge/fsr_shaders.h.
# Run in the PS5Build WSL distro after editing a shader:
#   bash /mnt/e/Pokopia-PS4/ps5/build/build-fsr-shaders.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SRC="$ROOT/gfx-bridge/shaders"
OUT="$ROOT/gfx-bridge/fsr_shaders.h"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
for name in easu rcas; do
  glslangValidator -V --target-env vulkan1.1 -I"$SRC" -o "$TMP/$name.spv" "$SRC/fsr_$name.comp" >/dev/null
  spirv-opt -O "$TMP/$name.spv" -o "$TMP/$name.spv"
done
python3 - "$TMP" "$OUT" <<'PY'
import struct, sys
tmp, out = sys.argv[1], sys.argv[2]
with open(out, "w", newline="\n") as f:
    f.write("/* GENERATED by ps5/build/build-fsr-shaders.sh - do not edit.\n"
            " * SPIR-V of gfx-bridge/shaders/fsr_easu.comp and fsr_rcas.comp (AMD FSR 1, MIT). */\n"
            "#ifndef POKOPIA_FSR_SHADERS_H\n#define POKOPIA_FSR_SHADERS_H\n\n#include <stdint.h>\n\n")
    for name in ("easu", "rcas"):
        data = open(f"{tmp}/{name}.spv", "rb").read()
        words = struct.unpack(f"<{len(data) // 4}I", data)
        f.write(f"static const uint32_t fsr_{name}_spv[{len(words)}] = {{\n")
        for i in range(0, len(words), 8):
            f.write("    " + ", ".join(f"0x{w:08x}" for w in words[i:i + 8]) + ",\n")
        f.write("};\n\n")
    f.write("#endif\n")
PY
echo "wrote $OUT"
