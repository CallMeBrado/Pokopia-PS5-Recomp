#!/usr/bin/env python3
"""Rasterise the on-screen keyboard's font (ASCII 32-126) into
gfx-bridge/osk_font.h: one 8-bit coverage atlas, one fixed-height cell per
glyph, cell width = advance.

    python ps5/scripts/gen-osk-font.py path/to/DejaVuSans.ttf

DejaVu Sans (https://dejavu-fonts.github.io/) is free to redistribute; its
licence notice is copied into the header."""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "gfx-bridge", "osk_font.h")
SIZE = 60         # font size in pixels (laid out for a 3840x2160 scanout)
CELL = 84         # cell height
BASELINE = 64     # baseline from the top of the cell

NOTICE = """Glyphs rasterised from DejaVu Sans 2.37. Fonts are (c) Bitstream (see below).
DejaVu changes are in public domain.
Bitstream Vera Fonts Copyright (c) 2003 by Bitstream, Inc. All Rights Reserved.
Bitstream Vera is a trademark of Bitstream, Inc.
Permission is hereby granted, free of charge, to any person obtaining a copy of
the fonts accompanying this license ("Fonts") and associated documentation
files, to reproduce and distribute the Font Software, including without
limitation the rights to use, copy, merge, publish, distribute, and/or sell
copies of the Font Software, subject to the conditions in the DejaVu LICENSE
(the copyright and trademark notices and this permission notice shall be
included in all copies of one or more of the Font Software typefaces; the Font
Software may be modified, altered or added to, provided the modified fonts do
not use the words "Bitstream" or "Vera"; the Font Software may not be sold by
itself). THE FONT SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND."""


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    font = ImageFont.truetype(sys.argv[1], SIZE)
    cells = []
    for code in range(32, 127):
        ch = chr(code)
        advance = max(1, int(round(font.getlength(ch))))
        left = min(0, font.getbbox(ch, anchor="ls")[0])
        width = advance - left + 2
        img = Image.new("L", (width, CELL), 0)
        ImageDraw.Draw(img).text((1 - left, BASELINE), ch, font=font, fill=255, anchor="ls")
        cells.append((code, img, advance, 1 - left))
    atlas_width = sum(c[1].width for c in cells)
    atlas = Image.new("L", (atlas_width, CELL), 0)
    x = 0
    entries = []
    for code, img, advance, origin in cells:
        atlas.paste(img, (x, 0))
        entries.append((code, x, img.width, advance, origin))
        x += img.width
    data = atlas.tobytes()
    with open(OUT, "w", newline="\n") as f:
        f.write("/* GENERATED by ps5/scripts/gen-osk-font.py - do not edit.\n")
        for line in NOTICE.splitlines():
            f.write(" * " + line + "\n")
        f.write(" */\n#ifndef POKOPIA_OSK_FONT_H\n#define POKOPIA_OSK_FONT_H\n\n#include <stdint.h>\n\n")
        f.write(f"enum {{ OSK_FONT_CELL = {CELL}, OSK_FONT_BASELINE = {BASELINE}, OSK_FONT_ATLAS_WIDTH = {atlas_width} }};\n\n")
        f.write("/* Per glyph (ASCII 32-126): atlas x, cell width, advance, pen origin within the cell. */\n")
        f.write("static const struct { uint16_t x, width, advance, origin; } osk_glyphs[95] = {\n")
        for code, gx, w, adv, origin in entries:
            f.write(f"    {{{gx}, {w}, {adv}, {origin}}}, /* {chr(code)!r} */\n")
        f.write("};\n\nstatic const uint8_t osk_font_atlas[OSK_FONT_CELL * OSK_FONT_ATLAS_WIDTH] = {\n")
        for i in range(0, len(data), 32):
            f.write("    " + ",".join(str(b) for b in data[i:i + 32]) + ",\n")
        f.write("};\n\n#endif\n")
    print(f"wrote {OUT} ({atlas_width}x{CELL})")


if __name__ == "__main__":
    main()
