#!/usr/bin/env python3
"""Generate the PlayStation Circle glyph for the title screen's "PRESS (A) BUTTON".

The title logo texture (1024x1024 BC7, drawn by the UI shader 2db3327d9fbc5bb3)
has the line "PRESS (A) BUTTON" baked in: a white disc with the letter cut out,
over a soft dark shadow. This script draws a replacement disc with the
PlayStation Circle symbol cut out (the A button maps to Circle), with a shadow
of the same falloff, encodes the 52x52 pixels around it as BC7 blocks and
writes gfx-bridge/ps_title_glyphs.h. The bridge patches those blocks into the
texture when it is first uploaded, recognising it by a hash of its blocks.

Everything in the header is drawn here; no game art is copied. The texture
dump (a PDMP file from debug/dump.req) is read only for that hash and to write
a before/after preview.

    python ps5/scripts/gen-ps-title.py dump-2db3327d9fbc5bb3-t128-1024-1024-1.bin

Measured from the dump: disc radius 23 px centred at (286, 655); shadow colour
(13, 11, 9) with alpha about 62*exp(-(r-23.5)/9) outside the disc; the cut-out
shows the shadow at alpha 75.
"""
import importlib.util
import os
import struct
import sys

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "gfx-bridge", "ps_title_glyphs.h")
SIZE = 1024
CENTER = (286.0, 655.0)
RADIUS = 23.2
REGION = (260, 628, 312, 680)  # x0, y0, x1, y1: multiples of 4
SHADOW = np.array([13.0, 11.0, 9.0])
CUT_ALPHA = 75.0
RING_OUTER, RING_WIDTH = 12.5, 4.2
SS = 8

spec = importlib.util.spec_from_file_location("glyphs", os.path.join(HERE, "gen-ps-glyphs.py"))
glyphs = importlib.util.module_from_spec(spec)
spec.loader.exec_module(glyphs)


def coverage(d, edge):
    """Fraction of each pixel inside radius edge, from supersampled distances d."""
    return (d < edge).reshape(d.shape[0] // SS, SS, d.shape[1] // SS, SS).mean((1, 3))


def draw():
    x0, y0, x1, y1 = REGION
    w, h = x1 - x0, y1 - y0
    ys, xs = np.mgrid[0:h * SS, 0:w * SS]
    px = x0 + (xs + 0.5) / SS
    py = y0 + (ys + 0.5) / SS
    d = np.hypot(px - CENTER[0], py - CENTER[1])
    disc = coverage(d, RADIUS)
    ring = coverage(d, RING_OUTER) - coverage(d, RING_OUTER - RING_WIDTH)
    # pixel-centre distance for the shadow falloff
    yc, xc = np.mgrid[0:h, 0:w]
    dc = np.hypot(x0 + xc + 0.5 - CENTER[0], y0 + yc + 0.5 - CENTER[1])
    shadow_a = np.clip(62.0 * np.exp(-(dc - 23.5) / 9.0), 0, 62.0)
    # White disc over the shadow (straight alpha), then the ring cut back to shadow.
    white_a = 255.0 * disc
    out_a = white_a + shadow_a * (1 - disc)
    out_rgb = (255.0 * white_a[..., None] + SHADOW * (shadow_a * (1 - disc))[..., None]) / np.maximum(out_a, 1)[..., None]
    cut = ring * disc
    out_rgb = out_rgb * (1 - cut[..., None]) + SHADOW * cut[..., None]
    out_a = out_a * (1 - cut) + CUT_ALPHA * cut
    rgba = np.dstack([out_rgb, out_a]).clip(0, 255).round().astype(np.uint8)
    return Image.fromarray(rgba, "RGBA")


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    raw = open(sys.argv[1], "rb").read()
    assert raw[:4] == b"PDMP"
    w, h, fmt, _ = struct.unpack("<4I", raw[4:20])
    assert (w, h, fmt) == (SIZE, SIZE, 145), (w, h, fmt)
    blocks_all = bytearray(raw[20:20 + SIZE * SIZE])
    texture_hash = glyphs.fnv64(bytes(blocks_all))

    x0, y0, x1, y1 = REGION
    tile = draw()
    blocks = glyphs.encode(tile)
    bw = (x1 - x0) // 4
    before = glyphs.decode_dds(bytes(blocks_all), SIZE, SIZE)
    for row in range((y1 - y0) // 4):
        start = ((y0 // 4 + row) * (SIZE // 4) + x0 // 4) * 16
        blocks_all[start:start + bw * 16] = blocks[row * bw * 16:(row + 1) * bw * 16]
    after = glyphs.decode_dds(bytes(blocks_all), SIZE, SIZE)
    box = (60, 610, 590, 700)
    preview = Image.new("RGBA", (box[2] - box[0], 2 * (box[3] - box[1])), (64, 72, 64, 255))
    preview.alpha_composite(before.crop(box), (0, 0))
    preview.alpha_composite(after.crop(box), (0, box[3] - box[1]))
    path = os.path.join(os.path.dirname(os.path.abspath(sys.argv[1])), "title-ps.png")
    preview.convert("RGB").resize((preview.width * 2, preview.height * 2), Image.NEAREST).save(path)

    with open(OUT, "w", newline="\n") as f:
        f.write("/* GENERATED by ps5/scripts/gen-ps-title.py - do not edit.\n"
                " * The PlayStation Circle glyph (drawn by that script, BC7 blocks) patched over\n"
                " * the (A) of \"PRESS (A) BUTTON\" in the game's 1024x1024 BC7 title logo texture. */\n"
                "#ifndef POKOPIA_PS_TITLE_GLYPHS_H\n#define POKOPIA_PS_TITLE_GLYPHS_H\n\n#include <stdint.h>\n\n")
        f.write(f"/* FNV-1a over the texture's level-0 BC7 blocks as 64-bit words. */\n"
                f"#define PS_TITLE_TEXTURE_HASH UINT64_C({texture_hash:#018x})\n"
                f"#define PS_TITLE_TEXTURE_SIZE {SIZE}\n\n")
        f.write(f"static const uint8_t ps_title_circle[{len(blocks)}] = {{\n")
        for i in range(0, len(blocks), 16):
            f.write("    " + ", ".join(f"0x{b:02x}" for b in blocks[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("static const struct {\n    uint16_t x, y, width, height; /* pixels, multiples of 4 */\n"
                "    const uint8_t *blocks;\n} ps_title_patches[] = {\n")
        f.write(f"    {{{x0}, {y0}, {x1 - x0}, {y1 - y0}, ps_title_circle}},\n")
        f.write("};\n\n#endif\n")
    print(f"hash {texture_hash:#018x}; wrote {OUT} and {path}")


if __name__ == "__main__":
    main()
