import ctypes as c
import math
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
DLL = ROOT / 'remote-service/chiaki-ng/1.10.1/chiaki-ng-Win/libopus-0.dll'
CHANNELS = 2
RATE = 48000
STREAMS = 2
COUPLED = 0
FRAMES = 960
APPLICATION_AUDIO = 2049
SET_BITRATE = 4002
GET_FINAL_RANGE = 4031
RESET_STATE = 4028


def signature(library, name, result, *arguments):
    function = getattr(library, name)
    function.restype = result
    function.argtypes = arguments
    return function


def main():
    opus = c.CDLL(str(DLL))
    byte_ptr = c.POINTER(c.c_ubyte)
    pcm_ptr = c.POINTER(c.c_int16)
    int_ptr = c.POINTER(c.c_int)
    create_encoder = signature(opus, 'opus_multistream_encoder_create', c.c_void_p, c.c_int32,
                               c.c_int, c.c_int, c.c_int, byte_ptr, c.c_int, int_ptr)
    encode = signature(opus, 'opus_multistream_encode', c.c_int, c.c_void_p, pcm_ptr, c.c_int, byte_ptr, c.c_int32)
    encoder_ctl = signature(opus, 'opus_multistream_encoder_ctl', c.c_int, c.c_void_p, c.c_int)
    destroy_encoder = signature(opus, 'opus_multistream_encoder_destroy', None, c.c_void_p)
    get_size = signature(opus, 'opus_multistream_decoder_get_size', c.c_int32, c.c_int, c.c_int)
    init_decoder = signature(opus, 'opus_multistream_decoder_init', c.c_int, c.c_void_p, c.c_int32,
                             c.c_int, c.c_int, c.c_int, byte_ptr)
    decode = signature(opus, 'opus_multistream_decode', c.c_int, c.c_void_p, byte_ptr, c.c_int32,
                       pcm_ptr, c.c_int, c.c_int)
    decoder_ctl = signature(opus, 'opus_multistream_decoder_ctl', c.c_int, c.c_void_p, c.c_int)
    version = signature(opus, 'opus_get_version_string', c.c_char_p)().decode('ascii')
    mapping = (c.c_ubyte * CHANNELS)(0, 1)
    error = c.c_int()
    encoder = create_encoder(RATE, CHANNELS, STREAMS, COUPLED, mapping, APPLICATION_AUDIO, c.byref(error))
    assert encoder and error.value == 0
    packet = (c.c_ubyte * 4096)()
    source = (c.c_int16 * (CHANNELS * FRAMES))()
    for frame in range(FRAMES):
        source[2 * frame] = int(20000 * math.sin(2 * math.pi * 750 * frame / RATE))
        source[2 * frame + 1] = int(15000 * math.sin(2 * math.pi * 1500 * frame / RATE))
    try:
        assert encoder_ctl(encoder, SET_BITRATE, c.c_int(96000)) == 0
        size = encode(encoder, source, FRAMES, packet, len(packet))
        assert size > 0
        encoded_range = c.c_uint32()
        assert encoder_ctl(encoder, GET_FINAL_RANGE, c.byref(encoded_range)) == 0
    finally:
        destroy_encoder(encoder)

    state_bytes = get_size(STREAMS, COUPLED)
    state = c.create_string_buffer(state_bytes)
    decoded = (c.c_int16 * (CHANNELS * FRAMES))()
    assert init_decoder(state, RATE, CHANNELS, STREAMS, COUPLED, mapping) == 0
    assert decode(state, packet, size, decoded, FRAMES, 0) == FRAMES
    decoded_range = c.c_uint32()
    assert decoder_ctl(state, GET_FINAL_RANGE, c.byref(decoded_range)) == 0
    assert decoded_range.value == encoded_range.value
    assert decoder_ctl(state, RESET_STATE) == 0
    repeated = (c.c_int16 * (CHANNELS * FRAMES))()
    assert decode(state, packet, size, repeated, FRAMES, 0) == FRAMES
    assert bytes(decoded) == bytes(repeated)
    packet_lines = [', '.join(f'0x{byte:02x}' for byte in packet[offset:min(offset + 12, size)])
                    for offset in range(0, size, 12)]
    packet_text = ',\n    '.join(packet_lines)
    data = f'''/* Synthetic 750/1500 Hz stereo, 2 independent streams, generated by {version}. */
static const unsigned char packet[] = {{
    {packet_text}
}};
static const uint32_t final_range = UINT32_C(0x{encoded_range.value:08x});
'''
    Path(__file__).with_name('opus-vector.inc').write_text(data, encoding='ascii')
    print(f'{version}: {state_bytes} state bytes, {size} packet bytes, {FRAMES} PCM frames, final range 0x{encoded_range.value:08x}')


if __name__ == '__main__':
    main()
